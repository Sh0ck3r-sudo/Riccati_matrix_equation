// ================================================================
//  КЛАСС МАТРИЦЫ
//  Предоставляет основные операции для работы с матрицами:
//  сложение, умножение, транспонирование, норма, обращение и т.д.
// ================================================================
class Matrix {
public:
    int rows, cols; // размеры матрицы // 2 элементарные операции
    vector<double> d; // данные хранятся построчно // 1 элементарная операция

    Matrix() : rows(0), cols(0) {} // 2 элементарные операции
    Matrix(int r, int c) : rows(r), cols(c), d(r * c, 0.0) {} // 4 элементарные операции

    // Доступ к элементу (i, j) без проверки границ
    double& operator()(int i, int j) { return d[i * cols + j]; } // 4 элементарные операции
    const double& operator()(int i, int j) const { return d[i * cols + j]; } // 4 элементарные операции

    // Евклидова норма (Фробениуса) матрицы
    double norm() const {
        double s = 0.0; // 2 элементарные операции
        for (size_t i = 0; i < d.size(); ++i) { // 3n + 3 элементарные операции
            s += d[i] * d[i]; // 5 элементарных операций
        } // Итоговая сложность for:  8n + 3
        return sqrt(s); // 2 элементарные операции 
    } // Итоговая сложность norm(): 8n + 7


    // Транспонирование матрицы
    Matrix transpose() const {
        Matrix T(cols, rows); // 6 элементарных операций
        for (int i = 0; i < rows; ++i) // 3n + 3 элементарных операций
            for (int j = 0; j < cols; ++j) // 3n + 3 элементарных операций
                T(j, i) = (*this)(i, j); // 9 элементарных операций
            // Итоговая сложность for: 12n + 3 элементарных операций
        // Итоговая сложность for: 12n^2 + 6n + 3
        return T; // 1 элементарная операция
    } // Итоговая сложность transpose(): 12n^2 + 6n + 10
 
    // Приведение квадратной матрицы к симметричному виду
    // Используется для обеспечения симметрии P(t)
    Matrix makeSymmetric() const {
        Matrix S = *this; // 3 элементарные операции
        if (rows != cols) return S; // 3 элементарные операции
        for (int i = 0; i < rows; ++i) // 3n + 3 элементарные операции
            for (int j = i + 1; j < cols; ++j) { // 3n - 3i + 1
                double val = 0.5 * (S(i, j) + S(j, i)); // 12 элементарных операций
                S(i, j) = val; // 5 элементарных операций
                S(j, i) = val; // 5 элементарных операций
            } // Итоговая сложность for: 25n - 3i + 1 элементарных операций
        // Итоговая сложность for:  24n^2 + 3n 
        return S; // 1 элементарная операция
    } // Итоговая сложность для makeSymmetric: 24n^2 + 6n + 10

    // Поэлементное сложение матриц
    Matrix operator+(const Matrix& B) const {
        Matrix C(rows, cols); // 6 элементарных операций
        for (size_t k = 0; k < d.size(); ++k) // 4n + 4 элементарных операций
            C.d[k] = d[k] + B.d[k]; // 7 элементарных операций
        // Итогоавя сложность for: 11n + 4
        return C; // 1 элементарная операция
    } // Итоговая сложность для operator+: 11n + 11

    // Поэлементное вычитание матриц
    Matrix operator-(const Matrix& B) const {
        Matrix C(rows, cols); // 6 элементарных операций
        for (size_t k = 0; k < d.size(); ++k) // 4n + 4 элементарных операций
            C.d[k] = d[k] - B.d[k]; // 7 элементарных операций
        // Итоговая сложность for: 11n + 4
        return C; // 1 элементарная операция
    } // Итоговая сложность operator-: 11n + 11

    // Умножение матрицы на скаляр
    Matrix operator*(double s) const {
        Matrix C(rows, cols); // 6 элементарных операций
        for (size_t k = 0; k < d.size(); ++k) // 4n + 4 элементарных операций
            C.d[k] = d[k] * s; // 5 элементарных операций
        // Итоговая сложность for: 9n + 4
        return C; // 1 элементарная операция
    } // Итоговая сложность для operator*: 9n + 11

    // Умножение матриц (A * B)
    // Размеры должны быть согласованы: cols == B.rows
    Matrix operator*(const Matrix& B) const {
        if (cols != B.rows) // 1 элементарная операция
            throw runtime_error("Ошибка умножения: несовпадение размерностей!"); // 1 элементарная операция (не выполняется)
        Matrix C(rows, B.cols); // 6 элементарных операций
        // Классический тройной цикл с пропуском нулевых элементов (оптимизация)
        for (int i = 0; i < rows; ++i) // 3n + 3 элементарных операций
            for (int k = 0; k < cols; ++k) // 3n + 3 элементарных операций
                if (fabs((*this)(i, k)) > 1e-15)   // если элемент не слишком мал // 6 элементарных операций
                    for (int j = 0; j < B.cols; ++j) // 4n + 4 элементарных операций
                        C(i, j) += (*this)(i, k) * B(k, j); // 15 элементарных операций
                    // Итоговая сложность for: 19n + 4
            // Итоговая сложность for: 19n^2 + 13n + 3
        // Итоговая сложность for: 19n^3 + 13n^2 + 6n + 3
        return C; // 1 элементарная операция
    } // Итоговая сложность для operator*: 19n^3 + 13n^2 + 6n + 11

    // Обращение квадратной матрицы методом Гаусса-Жордана
    // Возвращает обратную матрицу, выбрасывает исключение, если матрица вырождена
    Matrix inverse() const {
        if (rows != cols) // 1 элементарная операция
            throw runtime_error("Матрица должна быть квадратной для обращения!"); // 1 элементарная операция (не выполняется)
        int n = rows; // 2 элементарные операции
        // Создаём расширенную матрицу [A | I]
        Matrix Aug(n, 2 * n); // 7 элементарных операций
        for (int i = 0; i < n; ++i) { // 3n + 3 элементарных операций
            for (int j = 0; j < n; ++j) // 3n + 3 элементарных операций
                Aug(i, j) = (*this)(i, j); // 9 элементарных операций
            // Итоговая сложность for: 12n + 3
            Aug(i, n + i) = 1.0; // 6 элементарных операций
        } // Итоговая сложность for: 12n^2 + 12n + 3
        // Прямой ход (приведение к верхнетреугольному виду)
        for (int i = 0; i < n; ++i) { // 3n + 3 элементарных операций
            // Выбор главного элемента в столбце i
            int pivot = i; // 2 элементарные операции
            for (int j = i + 1; j < n; ++j) // 3n - 3i + 1 элементарных операций
                if (fabs(Aug(j, i)) > fabs(Aug(pivot, i))) // 11 элементарных операций
                    pivot = j; // 1 элементарная операция
            // Итоговая сложность for: 15n - 3i + 1
            // Перестановка строк
            if (pivot != i) { // 1 элементарная операция
                swap_ranges(Aug.d.begin() + i * 2 * n, 
                            Aug.d.begin() + (i + 1) * 2 * n,
                            Aug.d.begin() + pivot * 2 * n); // 17 элементарных операций
            }
            double div = Aug(i, i); // 6 элементарных операций
            if (fabs(div) < 1e-14) // 2 элементарные операции
                throw runtime_error("Матрица сингулярна, обращение невозможно!"); // 1 элементарная операция (не выполняется)
            // Нормировка строки i
            for (int k = 0; k < 2 * n; ++k) // 4n + 4 элементарных операций
                Aug(i, k) /= div; // 6 элементарных операций
            // Итоговая сложность for: 10n + 4
            // Обнуление остальных строк в столбце i
            for (int j = 0; j < n; ++j) { // 3n + 3 элементарных операций
                if (j != i) { // 1 элементарная операция
                    double factor = Aug(j, i); // 6 элементарных операций
                    for (int k = 0; k < 2 * n; ++k) // 4n + 4 элементарных операций
                        Aug(j, k) -= factor * Aug(i, k); // 11 элементарных операций
                    // Итоговая сложность for: 15n + 4
                }
            } // Итоговая сложность for: 15n^2 + 14n + 3
        } // Итоговая сложность for: 15n^3 + 38n^2 + 42n + 3
        // Извлекаем обратную матрицу из правой половины расширенной
        Matrix Inv(n, n); // 6 элементарных операций
        for (int i = 0; i < n; ++i) // 3n + 3 элементарных операций
            for (int j = 0; j < n; ++j) // 3n + 3 элементарных операций
                Inv(i, j) = Aug(i, n + j); // 10 элементарных операций
            // Итоговая сложность for: 13n + 3
        // Итоговая сложность for: 13n^2 + 6n + 3
        return Inv; // 1 элементарная операция
    } // Итоговая сложность inverse(): 15n^3 + 63n^2 + 60n + 25

    // Вывод матрицы на экран (первые 12 знаков, до 6 знаков после запятой)
    void print(const string& title = "") const {
        if (!title.empty()) cout << "\n  " << title << ":\n"; // 3 элементарные операции
        for (int i = 0; i < rows; ++i) { // 3n + 3 элементарных операций
            cout << "    "; // 1 элементарная операция
            for (int j = 0; j < cols; ++j) { // 3n + 3 элементарных операций
                double val = (*this)(i, j); // 6 элементарных операций
                if (fabs(val) < 1e-9) val = 0.0;   // очистка малых чисел // 3 элементарные операции
                cout << setw(12) << fixed << setprecision(6) << val << " "; // 4 элементарные операции
            } // Итоговая сложность for: 16n + 3
            cout << "\n"; // 1 элементарная операция
        } // Итоговая сложность for: 16n^2 + 8n + 3
    } // Итоговая сложность print: 16n^2 + 8n + 6

    // Сохранение матрицы в файл (каждый элемент с 12 знаками после запятой)
    void saveToFile(const string& fname) const {
        ofstream f(fname); // 1 элементарная операция
        f << fixed << setprecision(12); // 3 элементарные операции
        for (int i = 0; i < rows; ++i) { // 3n + 3 элементарных операций
            for (int j = 0; j < cols; ++j) // 3n + 3 элементарных операций
                f << (*this)(i, j) << (j < cols - 1 ? " " : "\n"); // 9 элементарных операций
            // Итоговая сложность for: 12n + 3
        } // Итоговая сложность for: 12n^2 + 6n + 3
    } // Итоговая сложность для saveToFile: 12n^2 + 6n + 7
};

// ================================================================
//  ЧТЕНИЕ МАТРИЦ ИЗ ФАЙЛА
//  Формат: строки, содержащие числа (количество строк определяет число строк матрицы,
//  количество чисел в первой строке – число столбцов).
// ================================================================
Matrix readMatrix(const string& fname) {
    ifstream f(fname); // 1 элементарная операция
    if (!f.is_open()) // 3 элементарные операции
        throw runtime_error("Не удалось открыть файл: " + fname); // 1 элементарная операция (не выполняется)
    vector<vector<double>> data; // 1 элементарная операция
    string line; // 1 элементарная операция
    while (getline(f, line)) { // 2n + 2 элементарных операций
        if (line.empty()) continue; // пропуск пустых строк // 3 элементарные операции
        stringstream ss(line); // 1 элементарная операция
        double val; // 1 элементарная операция
        vector<double> row; // 1 элементарная операция
        while (ss >> val) row.push_back(val); // 2n + 1
        if (!row.empty()) data.push_back(row); // 3 элементарные операции
    } // Итоговая сложность while: 2n^2 + 12n + 2
    if (data.empty()) // 2 элементарные операции
        throw runtime_error("Файл пуст или некорректен: " + fname); // 1 элементарная операция (не выполняется)
    int r = data.size(); // 3 элементарные операции
    int c = data[0].size(); // 4 элементарные операции
    Matrix M(r, c); // 6 элементарных операций
    for (int i = 0; i < r; ++i) { // 3n + 3 элементарных операций
        if ((int)data[i].size() != c)  // 4 элементарные операции
            throw runtime_error("Строки разной длины в " + fname); // 1 элементарная операция (не выполняется)
        for (int j = 0; j < c; ++j) // 3n + 3 элементарных операций
            M(i, j) = data[i][j]; // 7 элементарных операций
        // Итоговая сложность for: 10n + 3
    } // Итоговая сложность for: 10n^2 + 7n + 3
    return M; // 1 элементарная операция
} // Итоговая сложность readMatrix: 12n^2 + 19n + 26

// ================================================================
//  КОНТЕКСТ ДЕСКРИПТОРНОЙ СИСТЕМЫ
//  Содержит матрицы A, S, Q, E, а также индексы дифференциальной (Id)
//  и алгебраической (Ia) частей (определяются по ненулевым диагональным элементам E).
// ================================================================
struct SystemContext {
    Matrix A, S, Q, E; // 8 элементарных операций
    vector<int> Id; // индексы дифференциальных переменных (E(i,i) != 0) // 1 элементарная операция
    vector<int> Ia; // индексы алгебраических переменных (E(i,i) == 0) // 1 элементарная операция
}; // Итоговая сложность SystemContext: 10 элементарных операций

// -----------------------------------------------------------------
// applyAlgebraicConstraints
// Принудительно накладывает алгебраические ограничения на матрицу P.
// Для дескрипторных систем с сингулярной E часть переменных является алгебраическими.
// В методе Шафии (Shafiee) алгебраические компоненты p_aa обнуляются,
// а перекрёстные p_ia вычисляются из алгебраического уравнения (блоки (i,k)).
// -----------------------------------------------------------------
void applyAlgebraicConstraints(Matrix& P, const SystemContext& ctx) {
    // Обнуляем диагональные элементы для алгебраических индексов (p_aa = 0)
    for (size_t idx = 0; idx < ctx.Ia.size(); ++idx) { // 5n + 5
        int k = ctx.Ia[idx]; // 4 элементарные операции
        P(k, k) = 0.0; // 5 элементарных операций
    } // Итоговая сложность for: 14n + 5
    for (size_t id_i = 0; id_i < ctx.Id.size(); ++id_i) { // 5n + 5
        int i = ctx.Id[id_i]; // 4 элементарные операции
        for (size_t id_k = 0; id_k < ctx.Ia.size(); ++id_k) { // 5n + 5
            int k = ctx.Ia[id_k]; // 4 элементарные операции
            if (fabs(ctx.A(k, k)) < 1e-12) continue;   // защита от деления на ноль // 8 элементарных операций
            // Вычисляем сумму Σ P(i,j)*A(j,k)
            double sum = 0.0; // 2 элементарные операции
            for (size_t id_j = 0; id_j < ctx.Id.size(); ++id_j) { // 5n + 5 
                int j = ctx.Id[id_j]; // 4 элементарные операции
                sum += P(i, j) * ctx.A(j, k); // 12 элементарных операций
            } // Итоговая сложность for: 21n +  5
            // Формула из статьи Shafiee (вывод из блока (i,k) алгебраического уравнения)
            double val = (-ctx.Q(i, k) / ctx.E(i, i) - sum) / ctx.A(k, k); // 20 элементарных операций
            P(i, k) = val; // 5 элементарных операций
            P(k, i) = val;   // симметричная матрица // 5 элементарных операций
        } // Итоговая сложность for: 21n^2 + 54n + 5
    } // Итоговая сложность for: 21n^3 + 54n^2 + 14n + 5
} // Итоговая сложность applyAlgebraicConstraints: 21n^3 + 54n^2 + 28n + 10

// -----------------------------------------------------------------
// F_riccati
// Вычисляет производную P' для дифференциальных компонент.
// Сначала вычисляется матрица M = E^T P A + A^T P E + Q - E^T P S P E,
// затем для каждой пары (i,j) из Id производная равна F(i,j)=M(i,j)/(E(i,i)*E(j,j)).
// Для алгебраических индексов F не определена (остаётся нулевой).
// -----------------------------------------------------------------
Matrix F_riccati(const Matrix& P, const SystemContext& ctx) {
    // Вычисляем M = A^T P E + E^T P A + Q - E^T P S P E
    Matrix M = ctx.A.transpose() * P * ctx.E 
             + ctx.E.transpose() * P * ctx.A
             + ctx.Q
             - ctx.E.transpose() * P * ctx.S * P * ctx.E; // 36n^2 + 18n + 31 элементарных операций
    Matrix F(P.rows, P.cols);   // результирующая матрица (обнулена) // 8 элементарных операций
    // Заполняем только блок, соответствующий дифференциальным переменным
    for (size_t ii = 0; ii < ctx.Id.size(); ++ii) { // 5n + 5 элементарных операций
        int i = ctx.Id[ii]; // 4 элементарные операции
        for (size_t jj = 0; jj < ctx.Id.size(); ++jj) { // 5n + 5 элементарных операций
            int j = ctx.Id[jj]; // 4 элементарные операции
            F(i, j) = M(i, j) / (ctx.E(i, i) * ctx.E(j, j)); // 21 элементарная операция
        } // Итоговая сложность for: 30n + 5
    } // Итогоая сложность for: 30n^2 + 14n + 5
    return F; // 1 элементарная операция
} // Итоговая сложность F_riccati: 66n^2 + 32n + 45

// -----------------------------------------------------------------
// rk4_step
// Один шаг метода Рунге-Кутты 4-го порядка для интегрирования P' = F_riccati(P).
// Выполняет 4 вычисления F, корректирует P на половинных и целых шагах,
// затем применяет алгебраические ограничения и симметризацию.
// -----------------------------------------------------------------
Matrix rk4_step(const Matrix& P, double h, const SystemContext& ctx) {
    Matrix K1 = F_riccati(P, ctx); // 66n^2 + 32n + 48 элементарных операций
    Matrix P1 = P + K1 * (0.5 * h); // 6 элементарных операций
    applyAlgebraicConstraints(P1, ctx); // учитываем алгебраические связи на половинном шаге // 21n^3 + 54n^2 + 28n + 10 элементарных операций
    Matrix K2 = F_riccati(P1, ctx); // 66n^2 + 32n + 48 элементарных операций
    Matrix P2 = P + K2 * (0.5 * h); // 6 элементарных операций
    applyAlgebraicConstraints(P2, ctx); // 21n^3 + 54n^2 + 28n + 10 элементарных операций
    Matrix K3 = F_riccati(P2, ctx); // 66n^2 + 32n + 48 элементарных операций
    Matrix P3 = P + K3 * h; // 5 элементарных операций
    applyAlgebraicConstraints(P3, ctx); // 21n^3 + 54n^2 + 28n + 10 элементарных операций
    Matrix K4 = F_riccati(P3, ctx); // 66n^2 + 32n + 48 элементарных операций
    Matrix P_next = P + (K1 + K2 * 2.0 + K3 * 2.0 + K4) * (h / 6.0); // 11 элементарных операций
    P_next = P_next.makeSymmetric(); // обеспечение симметрии // 24n^2 + 6n + 11 элементарных операций
    applyAlgebraicConstraints(P_next, ctx); // финальные ограничения // 21n^3 + 54n^2 + 28n + 10 элементарных операций
    return P_next; // 1 элементарная операция
} // Итоговая сложность rk4_step: 84n^3 + 504n^2 + 246n + 272

// -----------------------------------------------------------------
// getStart
// Получает 4 стартовые точки P[0]..P[3] для методов Милна
// С помощью 3-кратного вызова rk4_step, начиная с начального условия P0.
// -----------------------------------------------------------------
vector<Matrix> getStart(const Matrix& P0, double h, const SystemContext& ctx) {
    vector<Matrix> P(4, Matrix(P0.rows, P0.cols)); // 7 элементарных операций
    P[0] = P0.makeSymmetric(); // 24n^2 + 6n + 12 элементарных операций
    applyAlgebraicConstraints(P[0], ctx); // 21n^3 + 54n^2 + 28n + 11 элементарных операций
    for (int i = 1; i <= 3; ++i) // 3n + 1 элементарных операций
        P[i] = rk4_step(P[i-1], h, ctx); // 84n^3 + 504n^2 + 246n + 276 элементарных операций
    // Итоговая сложность for: 84n^4 + 504n^3 + 246n^2 + 279n + 1
    return P; // 1 элементарная операция
} // Итоговая сложность getStart: 84n^4 + 525n^3 + 324n^2 + 313n + 32

// -----------------------------------------------------------------
// solve_milne_explicit
// Явный метод Милна (экстраполяционный).
// Использует формулу: P_{n+1} = P_{n-3} + (4h/3)*(2F_n - F_{n-1} + 2F_{n-2}).
// Для хранения использует окно из 4 последних P и F.
// Возвращает матрицу P(T) в конечный момент времени.
// -----------------------------------------------------------------
Matrix solve_milne_explicit(double h, double T, const Matrix& P0, const SystemContext& ctx) {
    int N = ceil(T / h); // 4 элементарные операции
    h = T / N;   // коррекция шага, чтобы точно попасть в T // 2 элементарные операции
    vector<Matrix> P = getStart(P0, h, ctx); // 84n^4 + 525n^3 + 324n^2 + 313n + 34 элементарных операций
    vector<Matrix> Fv(4, Matrix(P0.rows, P0.cols)); // 7 элементарных операций
    for (int i = 0; i < 4; ++i) // 3n + 3 элементарных операций
        Fv[i] = F_riccati(P[i], ctx); // 66n^2 + 32n + 48 элементарных операций
    // Итоговая сложность for: 66n^3 + 32n^2 + 51n + 3
    Matrix P_curr; // 2 элементарные операции
    // Основной цикл: от i=3 до N-1 (индекс i соответствует номеру последнего вычисленного шага)
    for (int i = 3; i < N; ++i) { // 3n + 3 элементарных операций
        // Явная формула Милна
        P_curr = P[0] + (Fv[3]*2.0 - Fv[2] + Fv[1]*2.0) * (4.0*h/3.0); // 13 элементарных операций
        P_curr = P_curr.makeSymmetric(); // 24n^2 + 6n + 11 элементарных операций
        applyAlgebraicConstraints(P_curr, ctx); // 21n^3 + 54n^2 + 28n + 10 элементарных операций
        // Сдвиг окна
        P[0] = P[1]; P[1] = P[2]; P[2] = P[3]; P[3] = P_curr; // 11 элементарных операций
        Fv[0] = Fv[1]; Fv[1] = Fv[2]; Fv[2] = Fv[3]; // 9 элементарных операций
        Fv[3] = F_riccati(P_curr, ctx); // 66n^2 + 32n + 47 элементарных операций
    } // Итоговая сложность for: 21n^4 + 144n^3 + 66n^2 + 104n + 3
    return P[3]; // 2 элементарные операции
} // Итоговая сложность solve_milne_explicit: 105n^4 + 735n^3 + 422n^2 + 468n + 57

// -----------------------------------------------------------------
// solve_milne_implicit
// Неявный метод Милна (предиктор-корректор).
// Предиктор: P* = P_{n-3} + (4h/3)*(2F_n - F_{n-1} + 2F_{n-2})
// Корректор: P = P_{n-1} + (h/3)*(F(P*) + 4F_n + F_{n-1})
// Итерации корректора повторяются до достижения сходимости (EPS_ITER).
// -----------------------------------------------------------------
Matrix solve_milne_implicit(double h, double T, const Matrix& P0, const SystemContext& ctx) {
    int N = ceil(T / h); // 3 элементарные операции
    h = T / N; // 2 элементарные операции
    vector<Matrix> P = getStart(P0, h, ctx); // 84n^4 + 525n^3 + 324n^2 + 313n + 34 элементарные операции
    vector<Matrix> Fv(4, Matrix(P0.rows, P0.cols)); // 7 элементарных операций
    for (int i = 0; i < 4; ++i) // 3n + 3 элементарных операций
        Fv[i] = F_riccati(P[i], ctx); // 66n^2 + 32n + 48 элементарных операций
    // Итоговая сложность for: 66n^3 + 32n^2 + 51n + 3
    Matrix P_curr, Pc; // 4 элементарные операции
    for (int i = 3; i < N; ++i) { // 3n + 3 элементарные операции
        // ----- Предиктор (явный) -----
        Matrix Pp = P[0] + (Fv[3]*2.0 - Fv[2] + Fv[1]*2.0) * (4.0*h/3.0); // 15 элементарных операций
        Pc = Pp.makeSymmetric(); // 24n^2 + 6n + 11 элементарных операций
        applyAlgebraicConstraints(Pc, ctx); // 21n^3 + 54n^2 + 28n + 10 элементарных операций
        // ----- Корректор (итерационный) -----
        for (int it = 0; it < MAX_ITER; ++it) { // 3n + 3 элементарных операций
            Matrix F_pc = F_riccati(Pc, ctx); // 66n^2 + 32n + 48 элементарных операций
            Matrix Pnew = P[2] + (F_pc + Fv[3]*4.0 + Fv[2]) * (h/3.0); // 12 элементарных операций
            Pnew = Pnew.makeSymmetric(); // 24n^2 + 6n + 11 элементарных операций
            applyAlgebraicConstraints(Pnew, ctx); // 21n^3 + 54n^2 + 28n + 10 элементарных операций
            // Проверка сходимости
            if ((Pnew - Pc).norm() < EPS_ITER) { // 8n + 9 элементарных операций
                Pc = Pnew; // 1 элементарная операция (не выполняется)
                break; // 1 элементарных операций  (не выполняется)
            }
            Pc = Pnew; // 1 элементарная операция
        } // Итоговая сложность for: 21n^4 + 144n^3 + 74n^2 + 94n + 3
        // Сдвиг окна
        P[0] = P[1]; P[1] = P[2]; P[2] = P[3]; P[3] = Pc; // 11 элементарных операций
        Fv[0] = Fv[1]; Fv[1] = Fv[2]; Fv[2] = Fv[3]; // 9 элементарных операций
        Fv[3] = F_riccati(Pc, ctx); // 66n^2 + 32n + 47
    } // Итоговая сложность for: 21n^5 + 165n^4 + 218n^3 + 160n^2 + 109n + 3
    return P[3]; // 2 элементарные операции
} // Итоговая сложность solve_milne_implicit: 21n^5 + 249n^4 + 809n^3 + 516n^2 + 473n + 58

// -----------------------------------------------------------------
// calculateResidual
// Вычисляет невязку (норму) алгебраического уравнения Риккати:
//   R = E^T P A + A^T P E + Q - E^T P S P E
// Чем меньше норма, тем точнее решение удовлетворяет стационарному уравнению.
// -----------------------------------------------------------------
double calculateResidual(const Matrix& P, const SystemContext& ctx) {
    Matrix term1 = ctx.E.transpose() * P * ctx.A; // 12n^2 + 6n + 17 элементарных операций
    Matrix term2 = ctx.A.transpose() * P * ctx.E; // 12n^2 + 6n + 17 элементарных операций
    Matrix term3 = ctx.E.transpose() * P * ctx.S * P * ctx.E; // 12n^2 + 6n + 20 элементарных операций
    Matrix res = term1 + term2 + ctx.Q - term3; // 7 элементарных операций
    return res.norm(); // 8n + 8 элементарных операций
} // Итоговая сложность calculateResidual: 36n^2 + 26n + 69

